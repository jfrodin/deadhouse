"""Hand-designed proportional pixel font for Deadhouse ("Corvane Condensed").

Each glyph is 10 rows tall (rows 1..10 of an 11-row cell; row 0 is blank).
Capitals and digits occupy rows 1-8, the baseline is row 8, descenders use 9-10.
'#' is ink, '.' is empty. Glyph width is the string length.
"""

def _g(*rows):
    rows = list(rows)
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    while len(rows) < 10:
        rows.append("." * w)
    return rows


